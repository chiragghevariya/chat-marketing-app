    /*
    |--------------------------------------------------------------------------
    | Upload Disk (App\Services\ImageUploadService)
    |--------------------------------------------------------------------------
    |
    | The disk ImageUploadService writes listing/avatar media to. Set UPLOAD_DISK
    | to force a choice; otherwise it auto-selects: "s3" when an AWS_BUCKET is
